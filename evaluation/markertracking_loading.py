    """Load the reference's FK joint-center positions, one row per movement (same
    (tracked_start, tracked_end) window from load_markertracking_reference() lines
    up index-for-index with joint_pos's own sample axis, per NNODES_EARLIER above)."""
    rows = []
    for movement, trial in movements.items():
        path = os.path.join(root, f'{movement}_{trial}.mat')
        if not os.path.exists(path):
            continue
        data = loadmat(path, struct_as_record=False, squeeze_me=True)
        rows.append({
            'participant': 'Participant_02',
            'movement': movement,
            'trial': trial,
            'joint_names': list(np.atleast_1d(data['jointNames']).astype(str)),
            'joint_pos': np.asarray(data['jointPos']),
        })
    return pd.DataFrame(rows)
