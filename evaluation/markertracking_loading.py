"""Loading utilities for the MarkerTracking3D (Nitschke et al. 2023) sparse-tracking
experiment -- Participant_02, TODO.md Experiment 3 ("prior-based OCP excels at
sparse tracking").

Two entry points:

    load_markertracking_sims(...)       -- one row per (condition, movement, trial)
    load_markertracking_reference(...)  -- one row per movement (measured + inverse)

Both read plain v7 .mat files produced by scripts/convert_markertracking_to_plain.m
and scripts/convert_markertracking_reference.m. Those scripts must be run on the
lab workstation, not locally -- see convert_markertracking_to_plain.m's docstring:
the local mac copy of BioMAC-Sim-Toolbox has a MEX-cache bug where constructing a
Gait3d model (which load()-ing a Result object does) spuriously judges the cached
gait3d_pelvis213_al.o stale and recompiles a 16MB autogenerated derivative file
from scratch (~3h) on every single construction, even within one MATLAB session.
The workstation's toolbox copy does not reproduce this (verified: two loads in one
session, .o/.mexa64 mtimes unchanged) and is where the actual conversion ran.

Sim rows carry a nested `variables` DataFrame (one row per simulated/tracked
channel, from Collocation.extractData()): columns `type, name, unit, sim, mean,
var, segment, direction_x/y/z, position_x/y/z`. `sim` is always populated (one
point per collocation node -- length varies by trial, roughly 149-218 samples,
NOT resampled to a fixed grid like evaluation/gait_loading.py's 100-node angles).
`mean`/`var` are only populated for channels this condition actually tracked
(GRF, and whichever markers `tracked_markers` lists) -- every other row is the
model's prediction for a channel it never saw, which is exactly the held-out
signal TODO.md Experiment 3 needs to score sparsity against.

Reference rows carry two nested DataFrames of the same shape, `measured` (the
raw marker/GRF recording, ~378 samples, the whole trial -- not gait-cycle
segmented) and `inverse` (the same trial's IK/ID-derived angles/moments/
translations/markers, computed from the FULL dense marker set, independent of
any of our sparse-tracking sims). Neither depends on sparsity condition, so
there is one reference row per movement, not per (condition, movement).

To score held-out-channel error: take a sim row's `variables`, filter to rows
whose (type, name) is not in that row's tracked set (GRF is always tracked;
markers are tracked iff `name` is in `tracked_markers`), then join against the
matching reference row's `inverse.variables` on (type, name) and compare `sim`
to `mean`. Left as a follow-up -- this module only loads.
"""
import os

import numpy as np
import pandas as pd
from scipy.io import loadmat

MARKERTRACKING_SIM_ROOT = os.path.join('results_sim', 'MarkerTracking3D', 'Participant_02_converted')
MARKERTRACKING_REFERENCE_ROOT = os.path.join('results_sim', 'MarkerTracking3D', 'Participant_02', 'reference')
MARKERTRACKING_SIM_JOINTS_ROOT = os.path.join('results_sim', 'MarkerTracking3D', 'Participant_02_converted_joints')
MARKERTRACKING_REFERENCE_JOINTS_ROOT = os.path.join('results_sim', 'MarkerTracking3D', 'Participant_02', 'reference_joints')

# The 8 sparsity/prior conditions actually run for Participant_02 (see AGENTS.md /
# TODO.md Experiment 3). '_prior' suffix = prior-based OCP; no suffix = plain OCP
# baseline. Trust `tracked_markers` per row for what was actually sparse, not the
# folder name -- see convert_markertracking_to_plain.m.
CONDITIONS = [
    'normal', 'normal_prior',
    'sparse_ankle', 'sparse_ankle_prior',
    'sparse_ankle_hand', 'sparse_ankle_hand_prior',
    'sparse_knee_ankle_pelvis', 'sparse_knee_ankle_pelvis_prior',
    'distal', 'distal_prior',
]

# movement -> trial id, shared between the sim and reference file layouts.
MOVEMENTS = {
    'straightrunning': 'trial0025',
    'curvedrunning': 'trial0100',
    'vcut': 'trial0122',
}
REFERENCE_MOVEMENTS = {'standing': 'trial0002', **MOVEMENTS}


def _direction_position(struct, n):
    """`direction`/`position` come back as an Nx3 double matrix column (NaN-filled
    for non-marker rows); reshape defensively in case MATLAB squeezed a lone row.
    """
    direction = np.atleast_2d(struct.direction).reshape(n, -1) if n else np.zeros((0, 3))
    position = np.atleast_2d(struct.position).reshape(n, -1) if n else np.zeros((0, 3))
    return direction, position


def _variables_to_frame(struct):
    """Flatten a converted table2struct'd `variables`/`simVarTable` mat_struct into
    a DataFrame, one row per channel.
    """
    name = np.atleast_1d(struct.name)
    n = len(name)
    direction, position = _direction_position(struct, n)
    frame = {
        'type': np.atleast_1d(struct.type),
        'name': name,
        'unit': np.atleast_1d(struct.unit),
        'mean': list(np.atleast_1d(struct.mean)),
        'var': list(np.atleast_1d(struct.var)),
        'segment': np.atleast_1d(struct.segment),
        'direction_x': direction[:, 0], 'direction_y': direction[:, 1], 'direction_z': direction[:, 2],
        'position_x': position[:, 0], 'position_y': position[:, 1], 'position_z': position[:, 2],
    }
    if hasattr(struct, 'sim'):
        frame['sim'] = list(np.atleast_1d(struct.sim))
    return pd.DataFrame(frame)


def _row_from_sim_mat(path, condition, movement, trial):
    data = loadmat(path, struct_as_record=False, squeeze_me=True)
    tracked_markers = data['tracked_markers']
    tracked_markers = [str(tracked_markers)] if isinstance(tracked_markers, str) else list(tracked_markers)
    return {
        'participant': 'Participant_02',
        'condition': condition,
        'is_prior': condition.endswith('_prior'),
        'movement': movement,
        'trial': trial,
        'converged': bool(data['converged']),
        'tracked_markers': tracked_markers,
        'variables': _variables_to_frame(data['simVarTable']),
    }


def load_markertracking_sims(root=MARKERTRACKING_SIM_ROOT, conditions=CONDITIONS, movements=MOVEMENTS):
    """Load every condition x movement sim trial into one row per trial.

    `filename = {movement}_{trial}_{condition}.mat` under `root/{condition}/`,
    plus the standing pose at `root/standing_marker.mat` (condition/movement
    'standing', no sparsity variants -- it is a single marker-tracked pose, not
    part of the sparsity sweep). Missing files are skipped silently, matching
    evaluation/gait_loading.py's convention.
    """
    rows = []
    standing_path = os.path.join(root, 'standing_marker.mat')
    if os.path.exists(standing_path):
        rows.append(_row_from_sim_mat(standing_path, 'standing', 'standing', 'trial0002'))
    for condition in conditions:
        for movement, trial in movements.items():
            path = os.path.join(root, condition, f'{movement}_{trial}_{condition}.mat')
            if not os.path.exists(path):
                continue
            rows.append(_row_from_sim_mat(path, condition, movement, trial))
    return pd.DataFrame(rows)


# setup_motion_marker.m trims trackingData to
# [R_IC(1)-NNODES_EARLIER, R_IC(2)-1] (1-based, inclusive) before handing it to
# the collocation problem -- no resampling, so a sim's `sim` column is a literal
# contiguous slice of measured/inverse's own sample index at the same 175 Hz.
# NNODES_EARLIER=10 is hardcoded in run_motion_marker.m, uniformly across every
# condition/trial. Verified this reproduces every trial's actual sim node count
# (149/157/175 for straightrunning/curvedrunning/vcut) from movementEvents alone.
NNODES_EARLIER = 10


def _tracked_window(measured):
    """(start, end) 0-based half-open Python slice bounds into measured/inverse's
    sample axis matching a motion trial's sim window exactly (see NNODES_EARLIER
    above); (None, None) for movements with no R_IC events (standing -- a static
    pose tracked by run_standing_marker, not run_motion_marker)."""
    events = measured.movementEvents
    names, indices = np.atleast_1d(events.name), np.atleast_1d(events.index)
    ic_indices = indices[names == 'R_IC']
    if len(ic_indices) != 2:
        return None, None
    start, end = int(ic_indices[0]) - NNODES_EARLIER, int(ic_indices[1]) - 1  # 1-based, inclusive
    return start - 1, end  # 0-based, half-open


def load_markertracking_reference(root=MARKERTRACKING_REFERENCE_ROOT, movements=REFERENCE_MOVEMENTS):
    """Load the dense measured+inverse reference, one row per movement.

    `filename = {movement}_{trial}.mat` under `root`. Does not vary by sparsity
    condition -- join sim rows to this on `movement` (and `trial`) to compute
    held-out-channel error. `tracked_start`/`tracked_end` (0-based, half-open,
    NaN for standing) slice `measured`/`inverse` to the exact same window a sim
    row's `sim` column covers -- see NNODES_EARLIER above -- so e.g.
    `inverse.iloc[i].mean[tracked_start:tracked_end]` lines up index-for-index
    with a matching sim row's `variables.iloc[j].sim`, no resampling needed.
    """
    rows = []
    for movement, trial in movements.items():
        path = os.path.join(root, f'{movement}_{trial}.mat')
        if not os.path.exists(path):
            continue
        data = loadmat(path, struct_as_record=False, squeeze_me=True)
        measured, inverse = data['measured'], data['inverse']
        tracked_start, tracked_end = _tracked_window(measured)
        rows.append({
            'participant': 'Participant_02',
            'movement': movement,
            'trial': trial,
            'movement_type': str(measured.movementType),
            'is_symmetric': bool(measured.isSymmetric),
            'tracked_start': tracked_start,
            'tracked_end': tracked_end,
            'measured': _variables_to_frame(measured.variables),
            'inverse': _variables_to_frame(inverse.variables),
        })
    return pd.DataFrame(rows)


# --- Joint-center MPJPE (FK on both sides -- there is no direct mocap ground
# truth for joint CENTERS, only markers) -----------------------------------
#
# scripts/convert_markertracking_joints_sim.m and
# scripts/convert_markertracking_reference_joints.m FK-project each side's
# own q(t) (sim: pulled straight from result.X, which -- unlike
# Collocation.extractData()'s default `settings.angle` -- was never filtered
# down and so already has pelvis orientation; reference: the IK-derived
# `inverse` angles/translations, which are a plain table2struct dump with the
# full <Coordinate> set) onto the same 19 anatomical joint centers via
# Gait3d.simuMarker(jointTable, q), using the SAME model/joint table on both
# sides. This is a separate converted tree from the `variables`-table loaders
# above -- `joint_pos` is a dense (nSamples, nJoints, 3) array in meters, not
# a per-channel table.

def _row_from_joints_mat(path, condition, movement, trial):
    data = loadmat(path, struct_as_record=False, squeeze_me=True)
    return {
        'participant': 'Participant_02',
        'condition': condition,
        'is_prior': condition.endswith('_prior'),
        'movement': movement,
        'trial': trial,
        'converged': bool(data['converged']),
        'joint_names': list(np.atleast_1d(data['jointNames']).astype(str)),
        'joint_pos': np.asarray(data['jointPos']),
        # Full per-DOF q(t) (radians/meters, includes pelvis orientation) that
        # produced `joint_pos` via FK -- saved MATLAB-side by
        # convert_markertracking_joints_sim.m (S.q/S.dofNames) but not
        # previously surfaced here. `dof_names` order matches `q`'s rows and
        # is identical to Participant_02.osim's own CoordinateSet names (see
        # plot/skeleton_frames/figure05 mesh-render prep scripts), so this q
        # can be applied directly to that model with no name remapping.
        'dof_names': list(np.atleast_1d(data['dofNames']).astype(str)),
        'q': np.asarray(data['q']),  # (nDofs, nNodes)
    }


def load_markertracking_sim_joints(root=MARKERTRACKING_SIM_JOINTS_ROOT, conditions=CONDITIONS, movements=MOVEMENTS):
    """Load per-trial FK joint-center positions, one row per (condition, movement,
    trial) -- same file layout/condition set as load_markertracking_sims()."""
    rows = []
    standing_path = os.path.join(root, 'standing_marker.mat')
    if os.path.exists(standing_path):
        rows.append(_row_from_joints_mat(standing_path, 'standing', 'standing', 'trial0002'))
    for condition in conditions:
        for movement, trial in movements.items():
            path = os.path.join(root, condition, f'{movement}_{trial}_{condition}.mat')
            if not os.path.exists(path):
                continue
            rows.append(_row_from_joints_mat(path, condition, movement, trial))
    return pd.DataFrame(rows)


